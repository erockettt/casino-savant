"""Seeded blackjack Monte Carlo with a real shoe, cut card and a full rule set.

Strategy: rule-specific total-dependent basic strategy generated by the
infinite-deck solver, optionally with Hi-Lo index plays (Illustrious 18 subset)
and a true-count bet ramp.  Results report mean EV per initial unit with a 95%
confidence interval, plus EV by true count.
"""
from __future__ import annotations

import math
import random
from collections import defaultdict
from dataclasses import dataclass, field

from ..blackjack.infinite import InfiniteDeck
from ..blackjack.rules import BlackjackRules

HILO = (-1, 1, 1, 1, 1, 1, 0, 0, 0, -1)  # by point value index v-1 (1..10)


def _val_tag(v: int) -> int:
    return HILO[v - 1]


@dataclass
class SimConfig:
    rounds: int = 200_000
    seed: int = 1
    use_indices: bool = False
    bet_ramp: dict | None = None    # {true_count_floor: units}; default flat 1 unit; 0 units = sit out (watch only)
    count_rounding: str = "floor"


@dataclass
class SimResult:
    rounds: int                  # rounds observed (played + sat out); EV/SD are per observed round
    total_wagered: float
    net: float
    ev_per_round: float          # per initial unit
    ci95: tuple[float, float]
    sd_per_round: float
    ev_per_unit_wagered: float
    by_true_count: dict = field(default_factory=dict)
    config: dict = field(default_factory=dict)


class Shoe:
    def __init__(self, decks: int, pen: float, rng: random.Random, per_hand: bool = False):
        self.decks, self.pen, self.rng, self.per_hand = decks, pen, rng, per_hand
        self.shuffle()

    def shuffle(self):
        self.cards = [v for v in range(1, 11) for _ in range((16 if v == 10 else 4) * self.decks)]
        self.rng.shuffle(self.cards)
        self.pos = 0
        self.rc = 0
        self.cut = int(len(self.cards) * self.pen)

    def needs_shuffle(self) -> bool:
        return self.per_hand or self.pos >= self.cut

    def draw(self) -> int:
        c = self.cards[self.pos]
        self.pos += 1
        self.rc += _val_tag(c)
        return c

    def true_count(self) -> float:
        dr = (len(self.cards) - self.pos) / 52
        return self.rc / max(dr, 0.25)


def _total(cards):
    t = sum(cards)
    soft = 1 in cards and t + 10 <= 21
    return (t + 10 if soft else t), soft


# Hi-Lo index plays applied by the simulator (subset of the Illustrious 18 / Fab 4)
INDEX_PLAYS = {
    ("hard", 16, 10): (0, "S"), ("hard", 15, 10): (4, "S"), ("hard", 12, 3): (2, "S"), ("hard", 12, 2): (3, "S"),
    ("hard", 11, 1): (1, "D"), ("hard", 9, 2): (1, "D"), ("hard", 10, 1): (4, "D"), ("hard", 9, 7): (3, "D"),
    ("hard", 16, 9): (5, "S"), ("hard", 10, 10): (4, "D"),
}
NEG_INDEX_PLAYS = {("hard", 13, 2): (-1, "H"), ("hard", 12, 4): (0, "H"), ("hard", 12, 5): (-2, "H"),
                   ("hard", 12, 6): (-1, "H"), ("hard", 13, 3): (-2, "H")}


class BlackjackSim:
    def __init__(self, rules: BlackjackRules, cfg: SimConfig):
        self.r, self.cfg = rules, cfg
        self.table = InfiniteDeck(rules).strategy_table()
        self.rng = random.Random(cfg.seed)

    def _decide(self, cards, up, *, first: bool, can_split: bool, split_hand: bool, tc: float) -> str:
        total, soft = _total(cards)
        if total >= 21:
            return "S"
        two = len(cards) == 2
        if two and can_split and cards[0] == cards[1]:
            a = self.table[("pair", cards[0], up)]
            if a == "P":
                return "P"
        kind = "soft" if soft else "hard"
        if two:
            a = self.table[(kind, total, up)]
            if a == "D" and not (not split_hand or self.r.double_after_split):
                a = self.table[(kind + "_mc", total, up)]
            if a == "R" and not first:
                a = self.table[(kind + "_mc", total, up)]
            if a == "P":
                a = self.table[(kind + "_mc", total, up)]
        else:
            a = self.table[(kind + "_mc", total, up)]
        if self.cfg.use_indices and not soft:
            k = ("hard", total, up)
            if k in INDEX_PLAYS:
                idx, act = INDEX_PLAYS[k]
                if tc >= idx:
                    if act == "D" and two and (not split_hand or self.r.double_after_split) and self.r.can_double(total, False):
                        a = "D"
                    elif act == "S" and a != "R":
                        a = "S"
                elif act == "S" and a == "S":
                    a = "H"
            if k in NEG_INDEX_PLAYS:
                idx, act = NEG_INDEX_PLAYS[k]
                if tc < idx:
                    a = "H"
        if a == "D" and not (two and self.r.can_double(total, soft)):
            a = "H" if self.table[(kind + "_mc", total, up)] == "H" else "S"
        return a

    def _play_hand(self, shoe, cards, up, bet, *, first, n_hands_ref, split_hand, tc):
        """Return list of (final_total or 'bust', bet, is_split_aces)."""
        results = []
        while True:
            can_split = (len(cards) == 2 and cards[0] == cards[1] and n_hands_ref[0] < self.r.max_split_hands
                         and not (split_hand and cards[0] == 1 and not self.r.resplit_aces))
            a = self._decide(cards, up, first=first, can_split=can_split, split_hand=split_hand, tc=tc)
            if a == "R":
                return [("surrender", bet)]
            if a == "P":
                n_hands_ref[0] += 1
                pv = cards[0]
                out = []
                for _ in range(2):
                    h = [pv, shoe.draw()]
                    if pv == 1 and not self.r.hit_split_aces:
                        if h[1] == 1 and n_hands_ref[0] < self.r.max_split_hands and self.r.resplit_aces:
                            out += self._play_hand(shoe, h, up, bet, first=False, n_hands_ref=n_hands_ref, split_hand=True, tc=tc)
                        else:
                            out.append((_total(h)[0], bet))
                    else:
                        out += self._play_hand(shoe, h, up, bet, first=False, n_hands_ref=n_hands_ref, split_hand=True, tc=tc)
                return out
            if a == "D":
                cards = cards + [shoe.draw()]
                t = _total(cards)[0]
                return [("bust" if t > 21 else t, 2 * bet)]
            if a == "H":
                cards = cards + [shoe.draw()]
                if _total(cards)[0] > 21:
                    return [("bust", bet)]
                first = False
                continue
            return [(_total(cards)[0], bet)]

    def run(self) -> SimResult:
        r, cfg = self.r, self.cfg
        shoe = Shoe(r.decks, r.penetration, self.rng, per_hand=(r.shuffle != "shoe"))
        ramp = cfg.bet_ramp or {}
        n = 0
        sat_out = 0
        s1 = s2 = wag = 0.0
        by_tc = defaultdict(lambda: [0, 0.0, 0.0])
        for _ in range(cfg.rounds):
            if shoe.needs_shuffle():
                shoe.shuffle()
            tc_raw = shoe.true_count()
            tc = math.floor(tc_raw) if cfg.count_rounding == "floor" else round(tc_raw)
            bet = 1.0
            if ramp:
                keys = sorted(ramp)
                bet = ramp[keys[0]]
                for k in keys:
                    if tc >= k:
                        bet = ramp[k]
            sitting_out = bet <= 0
            if sitting_out:
                bet = 1.0  # phantom hand: consumes cards exactly like a real seat, but no money moves
            p = [shoe.draw()]
            up = shoe.draw()
            p.append(shoe.draw())
            hole = shoe.draw()
            dealer = [up, hole]
            pbj = _total(p)[0] == 21
            dbj = _total(dealer)[0] == 21
            net = 0.0
            wagered = bet
            if r.insurance_offered and r.dealer_peeks and up == 1 and cfg.use_indices and tc >= 3 and not pbj:
                ins = bet / 2
                wagered += ins
                net += 2 * ins if hole == 10 else -ins
            if pbj:
                if not dbj:
                    net += r.blackjack_payout * bet
            elif dbj and r.dealer_peeks:
                net -= bet
            else:
                hands = self._play_hand(shoe, p, up, bet, first=True, n_hands_ref=[1], split_hand=False, tc=tc)
                wagered += sum(b for _, b in hands) - bet  # extra money from doubles/splits
                if dbj:
                    # ENHC: the natural is revealed after the player has acted
                    if r.enhc_lose_doubles_and_splits:
                        net -= sum(b for _, b in hands)
                    else:
                        net -= bet
                else:
                    if any(h[0] not in ("bust", "surrender") for h in hands):
                        while True:
                            t, s = _total(dealer)
                            if t > 17 or (t == 17 and not (s and r.dealer_hits_soft_17)):
                                break
                            dealer.append(shoe.draw())
                    dt = _total(dealer)[0]
                    for res, b in hands:
                        if res == "surrender":
                            net -= b / 2
                        elif res == "bust":
                            net -= b
                        elif dt > 21 or res > dt:
                            net += b
                        elif res < dt:
                            net -= b
            if sitting_out:
                by_tc_obs = by_tc[max(-6, min(8, tc))]
                by_tc_obs[0] += 1
                by_tc_obs[1] += net
                by_tc_obs[2] += net * net
                n += 1
                sat_out += 1
                continue
            n += 1
            s1 += net
            s2 += net * net
            wag += wagered
            bt = by_tc[max(-6, min(8, tc))]
            bt[0] += 1
            bt[1] += net / bet
            bt[2] += (net / bet) ** 2
        mean = s1 / n
        sd = math.sqrt(max(s2 / n - mean * mean, 0))
        half = 1.96 * sd / math.sqrt(n)
        tc_rows = {}
        for k in sorted(by_tc):
            c, a, b2 = by_tc[k]
            m = a / c
            s = math.sqrt(max(b2 / c - m * m, 0))
            tc_rows[k] = {"rounds": c, "freq": c / n, "ev_per_unit": m, "ci95_half": 1.96 * s / math.sqrt(c)}
        return SimResult(n, wag, s1, mean, (mean - half, mean + half), sd, s1 / wag if wag else 0.0, tc_rows,
                         {"rules": r.describe(), "rounds": cfg.rounds, "seed": cfg.seed,
                          "indices": cfg.use_indices, "ramp": ramp, "rounds_sat_out": sat_out,
                          "rounds_played": n - sat_out})
