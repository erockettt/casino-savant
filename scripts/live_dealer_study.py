"""Research Q3: can Hi-Lo beat an 8-deck live-dealer shoe, and at what risk?

Writes docs/LIVE_DEALER_STUDY.md.   python scripts/live_dealer_study.py [--rounds 3000000]

Rule sets are TEMPLATES for typical online live-dealer studios (8 decks, S17,
3:2, no resplit, no surrender), not verified Bovada rules. Penetration is the
main unknown, so it is swept.
"""
from __future__ import annotations

import argparse
import math
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from casino_savant.blackjack.rules import BlackjackRules  # noqa: E402
from casino_savant.lab.blackjack_sim import BlackjackSim, SimConfig  # noqa: E402
from casino_savant.lab.risk import risk_of_ruin  # noqa: E402

ROUNDS_PER_HOUR = 50  # ASSUMPTION: typical live-dealer pace, not measured on Bovada

STRATEGIES = {
    "flat (no count)": (False, None),
    "spread 1-8": (True, {-99: 1, 2: 2, 3: 4, 4: 6, 5: 8}),
    "spread 1-16": (True, {-99: 1, 2: 4, 3: 8, 4: 12, 5: 16}),
    "wong out <+1, 1-8": (True, {-99: 0, 1: 1, 2: 2, 3: 4, 4: 6, 5: 8}),
}
RULESETS = {
    "peek": dict(dealer_peeks=True),
    "no hole card, lose doubles/splits": dict(dealer_peeks=False, enhc_lose_doubles_and_splits=True),
}


def job(args):
    rules, cfg = args
    return BlackjackSim(rules, cfg).run()


def pooled(results):
    n = sum(r.rounds for r in results)
    net = sum(r.net for r in results)
    wag = sum(r.total_wagered for r in results)
    m = net / n
    ss = sum((r.sd_per_round ** 2 + r.ev_per_round ** 2) * r.rounds for r in results)
    sd = math.sqrt(max(ss / n - m * m, 0))
    played = sum(r.config["rounds_played"] for r in results)
    return n, m, 1.96 * sd / math.sqrt(n), sd, (net / wag if wag else 0.0), wag / max(played, 1), played / n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rounds", type=int, default=3_000_000)
    ap.add_argument("--workers", type=int, default=4)
    a = ap.parse_args()
    t0 = time.time()
    lines = [
        "# Live-dealer blackjack study (research Q3)", "",
        f"Generated by `scripts/live_dealer_study.py --rounds {a.rounds}`. Rules: 8 decks, S17, 3:2, DAS, "
        "no resplit, no surrender. These are **template** rules typical of online live-dealer studios, not "
        f"verified Bovada rules. Pace assumption: {ROUNDS_PER_HOUR} rounds/hour (not measured). "
        "Units = minimum bet. Indices: Illustrious-18 subset. EV and SD are per round observed; "
        "\"wong out\" rounds where you sit out count as 0.", "",
        "Columns: **N0** = rounds needed for expected win to equal one standard deviation (lower is better). "
        "**RoR** = infinite-play risk of ruin (diffusion approximation).", "",
    ]
    seed = 10_000
    for rname, rkw in RULESETS.items():
        lines += [f"## Dealer rule: {rname}", "",
                  "| Penetration | Strategy | EV / round (units) | 95% CI ± | Return / unit bet | Avg bet | Play rate | SD | N0 (hours) | EV / hour | RoR 200u | RoR 500u |",
                  "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for pen in (0.5, 0.625, 0.75):
            rules = BlackjackRules(decks=8, surrender="none", max_split_hands=2, penetration=pen, **rkw)
            for sname, (idx, ramp) in STRATEGIES.items():
                per = a.rounds // a.workers
                jobs = [(rules, SimConfig(rounds=per, seed=seed + i, use_indices=idx, bet_ramp=ramp)) for i in range(a.workers)]
                seed += a.workers
                with ProcessPoolExecutor(a.workers) as ex:
                    n, m, h, sd, pu, avg_bet, play = pooled(list(ex.map(job, jobs)))
                if m - h > 0:
                    n0 = (sd / m) ** 2
                    n0s = f"{n0 / ROUNDS_PER_HOUR:,.0f}"
                    r200 = f"{risk_of_ruin(m, sd, 200):.1%}"
                    r500 = f"{risk_of_ruin(m, sd, 500):.1%}"
                else:
                    n0s, r200, r500 = "no edge", "100%", "100%"
                lines.append(f"| {pen:.1%} | {sname} | {m:+.4f} | {h:.4f} | {pu:+.3%} | {avg_bet:.2f} | {play:.0%} | "
                             f"{sd:.2f} | {n0s} | {m * ROUNDS_PER_HOUR:+.3f} | {r200} | {r500} |")
                print(lines[-1], flush=True)
        lines.append("")
    lines += [
        "## Reading the table", "",
        "- An edge is claimed only when the whole 95% CI is above zero. Otherwise the row says *no edge* and RoR is 100%.",
        "- Penetration is the dominant factor. Confirm it by counting how many cards are dealt before the shuffle "
        "over several shoes, then rerun with that value.",
        "- \"Wong out\" (watching low counts without betting) is the strongest tool *if* the table lets you sit out "
        "without a penalty or being removed. Many live-dealer tables limit seats or skipped rounds. Verify this.",
        "- EV / hour depends on the pace assumption. Multiply by your unit size to get dollars per hour.",
        "- RoR uses the per-round mean and SD from the simulation. It ignores table limits and bet-sizing errors, "
        "so it is optimistic.",
        "",
        f"_Runtime {time.time() - t0:.0f} s._", "",
    ]
    (ROOT / "docs" / "LIVE_DEALER_STUDY.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
